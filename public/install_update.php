foreach ($files as $path => $content) {
    $fullPath = $baseDir . '/' . $path;
    $dir = dirname($fullPath);
    if (!is_dir($dir)) {
        mkdir($dir, 0755, true);
        echo "Created directory: $dir\n";
    }
    
    // Backup
    if (file_exists($fullPath)) {
        copy($fullPath, $fullPath . '.bak');
        echo "Backed up: $path -> $path.bak\n";
    }
    
    // Write
    file_put_contents($fullPath, base64_decode(str_replace(array("\r", "\n"), '', $content)));
    echo "Updated: $path\n";
}

